function barcodeBars(code, width){
  let h = 2166136261;
  for (const c of code + "DV0409") { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); }
  const rnd = () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 1000) / 1000; };
  const raw = []; let x = 0;
  while (x < width) { const w = 1 + Math.floor(rnd() * 3.2); const g = 1 + Math.floor(rnd() * 2.6); raw.push({ x, w }); x += w + g; }
  const scale = width / x;
  return raw.map(b => ({ x: +(b.x * scale).toFixed(2), w: +(b.w * scale).toFixed(2) }));
}

